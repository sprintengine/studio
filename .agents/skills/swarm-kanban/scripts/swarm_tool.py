#!/usr/bin/env python3
"""Swarm coordination tool for specialist agents.

WARNING: Do not edit swarm/state.json directly.
All updates must go through this tool.
"""

from __future__ import annotations

import argparse
import json
import os
import time
from datetime import datetime, timezone
from pathlib import Path
from typing import Any, Dict, List, Optional

try:
    import yaml  # type: ignore
except ImportError as exc:
    raise SystemExit(
        "PyYAML is required. Install with: python3 -m pip install pyyaml"
    ) from exc


VALID_TASK_STATUSES = {"todo", "in_progress", "needs_input", "done"}
ACTIVE_TASK_STATUSES = {"in_progress", "needs_input"}
VALID_ROLES = {"architect", "product", "developer", "frontend", "tester", "security"}

PROMPTS_DIR = Path(__file__).resolve().parent.parent / "prompts"

STATE_NOTICE = (
    "DO NOT EDIT THIS FILE DIRECTLY. "
    "All updates must go through the swarm tool "
    "(swarm task status, swarm task log, swarm plan set, etc.). "
    "Direct edits will be overwritten and may corrupt swarm state."
)


