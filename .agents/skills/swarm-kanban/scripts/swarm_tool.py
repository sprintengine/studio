def cmd_init(args: argparse.Namespace) -> Dict[str, Any]:
    state_path = args.state
    if not state_path.exists():
        state_path.parent.mkdir(parents=True, exist_ok=True)
        initial: Dict[str, Any] = {
            "swarm": {"goal": getattr(args, "goal", "") or "", "planApproved": False, "status": "planning"},
            "tasks": [],
            "agents": {},
            "events": [],
            "artifacts": [],
            "roles": {},
        }
        save_state(state_path, initial)

    state = load_state(state_path)
    plan_path = state_path.parent / "plan.md"
    plan_exists = plan_path.exists()
    plan_ready = state.get("swarm", {}).get("planReady", False)

    if plan_exists and plan_ready:
        return {"ok": True, "role": "architect", "action": "stop", "message": "Plan is marked ready for user approval. Your work as architect is complete. Stop now."}

    if plan_exists:
        return {"ok": True, "role": "architect", "action": "stop", "message": f"Plan file exists at {plan_path} but has not been marked ready. Review it, ensure the task graph is submitted, then run: swarm plan ready"}

    goal = state.get("swarm", {}).get("goal") or "(not set — read the codebase for context)"
    prompt = load_prompt("architect")
    directive = (
        "\n\n---\n"
        "## Your Goal\n"
        f"{goal}\n\n"
        "## Steps\n"
        f"1. Read the codebase and understand what needs to be done\n"
        f"2. Write a detailed plan to `{plan_path}`\n"
        f"3. Create a task graph and save it to `swarm/tasks.json`\n"
        f"4. Run: `swarm plan validate --file swarm/tasks.json`\n"
        f"5. Run: `swarm plan set --file swarm/tasks.json`\n"
        f"6. Run: `swarm plan ready`\n"
        f"7. **Stop** — the user will review and approve before workers start\n\n"
        "**IMPORTANT: Do not edit swarm/state.json directly. "
        "All updates must go through the swarm tool.**"
    )
    return {"ok": True, "role": "architect", "action": "plan", "prompt": prompt + directive}


def cmd_join(args: argparse.Namespace) -> Dict[str, Any]:
    state = load_state(args.state)
    plan_approved = state.get("swarm", {}).get("planApproved", False)

    if not plan_approved:
        return {"ok": True, "role": args.role, "agentId": args.id, "action": "stop", "message": "The architect plan has not been approved yet. Stop and wait for the user to approve it."}

    ready = [t for t in state.get("tasks", []) if t.get("role") == args.role and task_is_ready(state, t)]

    if not ready:
        return {"ok": True, "role": args.role, "agentId": args.id, "action": "stop", "message": f"No tasks are currently ready for the '{args.role}' role. Either all tasks are complete or dependencies are not yet resolved. Stop now."}

    prompt = load_prompt(args.role)
    directive = (
        f"\n\n---\n"
        f"## Your First Action\n"
        f"You are agent `{args.id}` with role `{args.role}`.\n"
        f"There are **{len(ready)} task(s)** ready for your role.\n\n"
        f"Run:\n```\nswarm task next --role {args.role} --id {args.id}\n```\n\n"
        f"Complete the task, log evidence, mark it done, then loop back to `swarm task next`. "
        f"When no tasks remain, stop.\n\n"
        "**IMPORTANT: Do not edit swarm/state.json directly. "
        "All updates must go through the swarm tool.**"
    )
    return {"ok": True, "role": args.role, "agentId": args.id, "action": "work", "readyTaskCount": len(ready), "prompt": prompt + directive}


def cmd_task_list(args: argparse.Namespace) -> Dict[str, Any]:
    def run(state: Dict[str, Any]) -> Dict[str, Any]:
        ready = []
        for t in state.get("tasks", []):
            if getattr(args, "role", None) and t.get("role") != args.role:
                continue
            if task_is_ready(state, t):
                ready.append({"id": t.get("id"), "title": t.get("title"), "role": t.get("role"), "dependsOn": t.get("dependsOn", [])})
        return {"ok": True, "readyTasks": ready, "write": False}
    return with_locked_state(args.state, run)


def cmd_task_next(args: argparse.Namespace) -> Dict[str, Any]:
    def run(state: Dict[str, Any]) -> Dict[str, Any]:
        if not state.get("swarm", {}).get("planApproved", False):
            return {"ok": False, "error": "Plan not approved. Workers must wait.", "write": False}

        runtime = reconcile_agent(state, args.id, args.role)
        agent = runtime["agent"]
        active = runtime["activeTask"]
        if active:
            return {"ok": True, "claimed": False, "reason": "agent_already_has_active_task", "task": active, "agent": agent}

        for t in state.get("tasks", []):
            if t.get("role") != args.role or not task_is_ready(state, t):
                continue
            result = assign_task(state, t, args.id)
            recompute_phase(state)
            event = append_event(state, "task_claimed", args.id, f"{args.id} claimed {t.get('id')}.")
            return {"ok": True, "claimed": True, "task": t, "agent": result["agent"], "event": event}

        recompute_phase(state)
        return {"ok": True, "claimed": False, "reason": "no_ready_task", "message": f"No ready {args.role} tasks. Stop."}

    return with_locked_state(args.state, run)


def cmd_task_claim(args: argparse.Namespace) -> Dict[str, Any]:
    def run(state: Dict[str, Any]) -> Dict[str, Any]:
        if not state.get("swarm", {}).get("planApproved", False):
            return {"ok": False, "error": "Plan not approved.", "write": False}
        task = find_task(state, args.task_id)
        if not task_is_ready(state, task):
            return {"ok": False, "error": "Task is not ready.", "task": {"id": task.get("id"), "status": task.get("status")}, "write": False}
        result = assign_task(state, task, args.id)
        recompute_phase(state)
        event = append_event(state, "task_claimed", args.id, f"{args.id} claimed {args.task_id}.")
        return {"ok": True, "task": task, "agent": result["agent"], "event": event}
    return with_locked_state(args.state, run)


def cmd_task_status(args: argparse.Namespace) -> Dict[str, Any]:
    def run(state: Dict[str, Any]) -> Dict[str, Any]:
        task = find_task(state, args.task_id)
        actor = args.id or task.get("ownerAgentId") or task.get("role") or "agent"
        task["status"] = args.status
        if args.status == "in_progress" and not task.get("startedAt"):
            task["startedAt"] = now_iso()
        if args.status == "done":
            task["completedAt"] = now_iso()
        if getattr(args, "summary", None):
            ensure_evidence(task)["summary"] = args.summary
        if task.get("ownerAgentId"):
            agent = ensure_agent(state, task["ownerAgentId"], task.get("role"))
            if args.status == "in_progress":
                agent["status"] = "running"
                agent["currentTaskId"] = args.task_id
            elif args.status == "needs_input":
                agent["status"] = "needs_input"
                agent["currentTaskId"] = args.task_id
        cleared = []
        if args.status not in ACTIVE_TASK_STATUSES:
            cleared = clear_task_refs(state, args.task_id)
        recompute_phase(state)
        event = append_event(state, "task_status_changed", actor, f"{actor} moved {args.task_id} to {args.status}.")
        return {"ok": True, "task": task, "event": event, "clearedAgents": cleared}
    return with_locked_state(args.state, run)


def cmd_task_log(args: argparse.Namespace) -> Dict[str, Any]:
    def run(state: Dict[str, Any]) -> Dict[str, Any]:
        task = find_task(state, args.task_id)
        ev = ensure_evidence(task)
        if getattr(args, "summary", None):
            ev["summary"] = args.summary
        ev["touchedFiles"].extend(args.file or [])
        ev["commandsRan"].extend(args.command or [])
        ev["results"].extend(args.result or [])
        event = append_event(state, "task_evidence_appended", args.id, f"{args.id} logged evidence for {args.task_id}.")
        return {"ok": True, "task": task, "event": event}
    return with_locked_state(args.state, run)


def cmd_task_note(args: argparse.Namespace) -> Dict[str, Any]:
    def run(state: Dict[str, Any]) -> Dict[str, Any]:
        task = find_task(state, args.task_id)
        task.setdefault("notes", []).append(args.note)
        event = append_event(state, "task_note_added", args.id, f"{args.id} added note to {args.task_id}.")
        return {"ok": True, "task": task, "event": event}
    return with_locked_state(args.state, run)


def cmd_plan_validate(args: argparse.Namespace) -> Dict[str, Any]:
    tasks = load_tasks_payload(args)
    v = validate_task_graph(tasks)
    return {"ok": len(v["errors"]) == 0, "taskCount": len(tasks), "errors": v["errors"], "warnings": v["warnings"]}


def cmd_plan_set(args: argparse.Namespace) -> Dict[str, Any]:
    next_tasks = load_tasks_payload(args)
    v = validate_task_graph(next_tasks)
    if v["errors"]:
        return {"ok": False, "errors": v["errors"], "warnings": v["warnings"]}

    def run(state: Dict[str, Any]) -> Dict[str, Any]:
        if state.get("swarm", {}).get("planApproved", False) and not getattr(args, "force", False):
            return {"ok": False, "error": "Plan already approved. Use --force to override.", "write": False}
        state["tasks"] = next_tasks
        swarm = state.setdefault("swarm", {})
        swarm.update({"planReady": False, "planReadyAt": None, "planReadyBy": None, "taskGraphReplacedAt": now_iso()})
        for agent in state.get("agents", {}).values():
            if isinstance(agent, dict):
                agent.update({"status": "idle", "currentTaskId": None})
        recompute_phase(state)
        event = append_event(state, "tasks_replaced", args.actor, f"{args.actor} set task graph ({len(next_tasks)} tasks).")
        return {"ok": True, "taskCount": len(next_tasks), "warnings": v["warnings"], "event": event}

    return with_locked_state(args.state, run)


def cmd_plan_ready(args: argparse.Namespace) -> Dict[str, Any]:
    def run(state: Dict[str, Any]) -> Dict[str, Any]:
        swarm = state.setdefault("swarm", {})
        if swarm.get("planApproved", False) and not getattr(args, "force", False):
            return {"ok": False, "error": "Plan already approved.", "write": False}

        tasks = [normalize_task(t) for t in state.get("tasks", [])]
        v = validate_task_graph(tasks)
        if v["errors"]:
            return {"ok": False, "error": "Task graph has errors. Fix before marking ready.", "errors": v["errors"]}

        task_graph_set = bool(swarm.get("taskGraphReplacedAt")) or any(
            e.get("type") == "tasks_replaced" for e in state.get("events", [])
        )
        if not task_graph_set and not getattr(args, "force", False):
            return {"ok": False, "error": "Run `swarm plan set` before marking ready."}

        plan_path = getattr(args, "plan", None) or args.state.parent / "plan.md"
        warnings = list(v["warnings"])
        if not plan_path.exists():
            if not getattr(args, "force", False):
                return {"ok": False, "error": f"Plan file not found: {plan_path}.", "write": False}
            warnings.append(f"Plan file not found: {plan_path}.")

        swarm.update({"planReady": True, "planReadyAt": now_iso(), "planReadyBy": args.actor})
        event = append_event(state, "plan_ready", args.actor, f"{args.actor} marked plan ready for review.")
        return {"ok": True, "planReady": True, "warnings": warnings, "event": event}

    return with_locked_state(args.state, run)


def cmd_summary(args: argparse.Namespace) -> Dict[str, Any]:
    def run(state: Dict[str, Any]) -> Dict[str, Any]:
        return {"ok": True, "summary": build_run_summary(state), "write": False}
    return with_locked_state(args.state, run)


